"""Profile-aware lecture context without hidden scoring material."""

import asyncio
import json
import unittest
from pathlib import Path

from pydantic_ai.messages import ModelResponse, TextPart, UserPromptPart
from pydantic_ai.models.function import FunctionModel

from educagent_sdk import load_content_pack
from educagent_sdk.demo import DemoController
from educagent_sdk.lesson_samples import load_lesson_samples


ROOT = Path(__file__).resolve().parents[1]


class LessonTutorContextTest(unittest.TestCase):
    def test_definition_quote_is_exact_and_does_not_call_model_or_award_credit(self):
        registry = json.loads((ROOT / "content/modules.json").read_text(encoding="utf-8"))
        module = next(m for m in registry["modules"] if m["module_id"] == "causality_m0")
        for profile in ("general", "medical"):
            pack = load_content_pack(ROOT / module["profile_pack_paths"][profile])
            demo = DemoController(pack)
            demo.start(preferred_activity_ids=("association-is-not-causation.practice",), route_scope="preferred")
            def forbidden(*args):
                raise AssertionError("Verified quotation must not be generated by a model")
            state = asyncio.run(demo.send_message_with_tutor(
                request_id="definition.quote", text="so what is the definition of association?",
                model=FunctionModel(forbidden), unguarded=True))
            text = state["conversation"][-1]["text"]
            self.assertIn('Otherwise, X and Y are dependent', text)
            self.assertIn('\n\n> "We call X independent', text)
            self.assertIn('[Publisher source](https://mitpress.mit.edu/', text)
            self.assertIn("p. 213", text)
            self.assertIn("Appendix A.1(vi)", text)
            self.assertNotIn("sunny", text.lower())
            self.assertNotIn("ice-cream", text.lower())
            self.assertFalse(state["can_continue"])
            self.assertEqual(state["completed_concept_ids"], ())

    def test_sales_quiz_withholds_solution_and_rejects_explanation_before_question(self) -> None:
        registry = json.loads((ROOT / "content/modules.json").read_text(encoding="utf-8"))
        module = next(m for m in registry["modules"] if m["module_id"] == "causality_m0")
        pack = load_content_pack(ROOT / module["profile_pack_paths"]["general"])
        activity = next(a for a in pack.activities if a.activity_id == "association-is-not-causation.practice")
        demo = DemoController(pack)
        demo.start(preferred_activity_ids=(activity.activity_id,), route_scope="preferred")
        captured = []
        def reply(messages, _info):
            context = json.loads(next(p.content for m in reversed(messages) for p in m.parts
                                     if isinstance(p, UserPromptPart) and isinstance(p.content,str)))
            captured.append(context)
            return ModelResponse(parts=[TextPart(
                "Sunny weather might raise both sales. What comparison would test a direct effect?")])
        state = asyncio.run(demo.send_message_with_tutor(
            request_id="sales.hint", text="If both sales go up together, why can't we say one causes the other?",
            model=FunctionModel(reply), unguarded=True))
        for context in captured:
            self.assertIsNone(context["visible_lesson"])
            self.assertNotIn("concept_explanation",context)
            self.assertNotIn("sunny weather",json.dumps(context).lower())
            self.assertEqual(context["assessment_help"],{"phase":"topic_before_answer"})
            self.assertEqual(context["requested_response"],"one_question")
        self.assertNotIn("Sunny weather",state["conversation"][-1]["text"])
        self.assertTrue(state["conversation"][-1]["text"].endswith("?"))

    def test_unanswered_topic_hides_the_worked_solution_even_for_explanation_requests(self) -> None:
        samples = load_lesson_samples(load_content_pack(ROOT / "content/causality_m0_full.json"),
                                      ROOT / "content/foundation_lesson_samples.json")
        for profile_id, pack in samples.items():
            with self.subTest(profile=profile_id):
                captured = []

                def reply(messages, _info):
                    for message in messages:
                        for part in message.parts:
                            if isinstance(part, UserPromptPart) and isinstance(part.content, str):
                                captured.append(json.loads(part.content))
                    return ModelResponse(parts=[TextPart(content="The displayed pattern is an association, not yet an intervention effect.")])

                controller = DemoController(pack, mode="guarded_tutor")
                controller.start(session_id=f"context.{profile_id}")
                state = asyncio.run(controller.send_message_with_tutor(
                    request_id=f"context.{profile_id}.question", text="What did the worked example mean?",
                    model=FunctionModel(reply), unguarded=True))
                context = captured[-1]
                self.assertEqual(context["profile_id"], profile_id)
                self.assertIsNone(context["visible_lesson"])
                self.assertEqual(context["assessment_help"]["phase"], "topic_before_answer")
                self.assertNotIn("concept_explanation", context)
                self.assertFalse(state["can_continue"])
                self.assertEqual(state["completed_concept_ids"], ())


if __name__ == "__main__":
    unittest.main()
